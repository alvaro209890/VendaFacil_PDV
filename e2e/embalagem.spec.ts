import { test, expect } from '@playwright/test';
const api = process.env.VF_EMBALAGEM_API || 'http://127.0.0.1:3121';
const fixture = {usuario:'e2e-carrinho',nome:'Teste descartável',senha:'fixture-e2e-carrinho'};
let token:string;
test.beforeAll(async ({request})=>{
  let r=await request.post(`${api}/api/auth/login`,{data:fixture});
  if(r.status()===401) r=await request.post(`${api}/api/auth/registro`,{data:fixture});
  expect(r.status()).toBe(200); token=(await r.json()).token;
});
test('T11: cadastro, entrada de 2 carteiras, venda mista e recusa',async({page,request})=>{
  await page.addInitScript(t=>localStorage.setItem('vf_token',t),token);
  await page.goto('/produtos');
  await page.getByRole('button',{name:'+ Novo',exact:true}).click();
  await page.getByPlaceholder('Ex: Arroz 5kg').fill('Palheiros T11');
  await page.getByPlaceholder('789...').fill('7891000888001');
  await page.getByRole('checkbox',{name:'Também vende por unidade'}).check();
  await page.getByLabel('Nome da embalagem').fill('CARTEIRA');
  await page.getByText('Qtd por compra',{exact:true}).locator('..').locator('input').fill('20');
  await page.getByLabel('Preço da embalagem fechada',{exact:true}).fill('20');
  await page.getByLabel('Preço da unidade',{exact:true}).fill('2');
  await page.getByLabel('Código da unidade',{exact:true}).fill('AVULSO-T11');
  await page.getByRole('button',{name:'Criar Produto',exact:true}).click();
  await expect(page.getByText('Produto criado!',{exact:true})).toBeVisible();
  const xml='<NFe><infNFe><ide><mod>55</mod><nNF>11</nNF></ide><emit><xNome>Fornecedor teste</xNome></emit><det><prod><cEAN>7891000888001</cEAN><xProd>Palheiros T11</xProd><uCom>CARTEIRA</uCom><qCom>2</qCom><vUnCom>10</vUnCom></prod></det></infNFe></NFe>';
  await page.locator('input[type=file]').setInputFiles({name:'compra.xml',mimeType:'text/xml',buffer:Buffer.from(xml)});
  await expect(page.getByRole('dialog').filter({hasText:'Confirmar importação'})).toBeVisible();
  await page.getByRole('button',{name:'Confirmar importação',exact:true}).click();
  await expect(page.getByText(/Importado!/)).toBeVisible();
  const h={Authorization:`Bearer ${token}`};
  const produtos=(await (await request.get(`${api}/api/produtos`,{headers:h})).json()).produtos;
  const p=produtos.find((p:{nome:string})=>p.nome==='Palheiros T11'); expect(p.estoque).toBe(40);
  await page.goto('/pdv');
  const busca=page.getByPlaceholder(/Bipe o código/);
  await busca.fill('7891000888001'); await busca.press('Enter');
  await busca.fill('AVULSO-T11'); await busca.press('Enter');
  await page.getByLabel('Quantidade de Palheiros T11 UN',{exact:true}).fill('3');
  await page.reload();
  await expect(page.getByLabel('Quantidade de Palheiros T11 CARTEIRA',{exact:true})).toHaveValue('1');
  await expect(page.getByLabel('Quantidade de Palheiros T11 UN',{exact:true})).toHaveValue('3');
  await page.screenshot({path:'output/playwright/embalagem-carrinho.png',fullPage:true});
  await page.getByPlaceholder('0,00',{exact:true}).fill('26');
  await page.getByRole('button',{name:/finalizar venda/i}).click();
  await expect(page.getByText(/Venda finalizada!/)).toBeVisible();
  const apos=await request.get(`${api}/api/produtos/${p.id}`,{headers:h}); expect((await apos.json()).produto.estoque).toBe(17);
  await busca.fill('7891000888001'); await busca.press('Enter');
  await expect(page.getByText(/Estoque insuficiente/)).toBeVisible();
  await expect(page.getByLabel('Quantidade de Palheiros T11 CARTEIRA',{exact:true})).toHaveCount(0);
});
